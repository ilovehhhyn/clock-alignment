"""Wrap the artifact-format site source into one standalone HTML document for GitHub Pages.

Usage: python3 scripts/build_site.py
Reads docs/clock-alignment.html, which has no document skeleton because the artifact host adds one, and writes
docs/index.html with a doctype, html, head and body around the same content. The figures stay at docs/figures.
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "clock-alignment.html"
OUTPUT = ROOT / "docs" / "index.html"
HEAD_END_TAG = "</style>"  # everything up to and including the page's style block belongs in the head
HEAD_START = ('<!doctype html>\n<html lang="en">\n<head>\n'
              "<!-- @generated by scripts/build_site.py from docs/clock-alignment.html. Do not edit by hand. -->\n"
              '<meta charset="utf-8">\n'
              '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n')


def build(source_text: str) -> str:
    """Return the standalone document; the source must end its head section with one style block."""
    head_part, separator, body_part = source_text.partition(HEAD_END_TAG)
    if separator == "":
        raise ValueError(f"{SOURCE} must contain a {HEAD_END_TAG} tag that ends its head section")
    return HEAD_START + head_part + separator + "\n</head>\n<body>" + body_part + "</body>\n</html>\n"


def main() -> None:
    OUTPUT.write_text(build(SOURCE.read_text()))
    print(OUTPUT)


if __name__ == "__main__":
    main()
